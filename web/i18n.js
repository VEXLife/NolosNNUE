const dict = { zh, en };
let lang = 'zh';

export function detectLang(saved) {
  if (saved && dict[saved]) return saved;
  return /^zh\b/i.test(navigator.language || '') ? 'zh' : 'en';
}
export function setLang(value) { lang = dict[value] ? value : 'en'; document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en'; }
export function getLang() { return lang; }
export function t(key, params = {}) {
  const raw = dict[lang][key] ?? en[key] ?? key;
  if (typeof raw !== 'string') return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k) => params[k] ?? '');
}
// Static markup: data-i18n (text), data-i18n-title, data-i18n-placeholder, data-i18n-aria.
export function translateDom(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  document.title = t('title');
}
